/**
 * Runtime Target: node-typescript-express
 *
 * Compiles web-api architecture to Node.js + TypeScript + Express 5.
 * Same architecture, language, and DB driver (better-sqlite3) as
 * `node-typescript`; the only delta is the framework — Express instead
 * of Hono.
 *
 * Why this exists: load-bears the RuntimeTarget abstraction. Iterations
 * 3-6 pulled five Hono-specific assumptions onto RuntimeTarget hooks
 * (mandatoryImports, stripImportPatterns, generateServerEntry,
 * generateModuleStub, generateServiceTests). This target exercises every
 * one of them with a different framework — proving the abstraction is
 * actually load-bearing, not just theoretical.
 */

