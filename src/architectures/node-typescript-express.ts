function generateExpressServiceTests(svc: ServiceDescriptor): string {
  const lines: string[] = [];
  lines.push(`/**`);
  lines.push(` * ${svc.name} — Generated Tests`);
  lines.push(` * AUTO-GENERATED by Phoenix VCS`);
  lines.push(` */`);
  lines.push(``);
  lines.push(`import { describe, it, expect } from 'vitest';`);

  for (const mod of svc.modules) {
    const importName = mod.replace('.ts', '').replace(/-/g, '_');
    lines.push(`import ${importName} from '../${mod.replace('.ts', '.js')}';`);
  }

  lines.push(``);
  lines.push(`describe('${svc.name} modules', () => {`);

  for (const mod of svc.modules) {
    const importName = mod.replace('.ts', '').replace(/-/g, '_');
    const displayName = mod.replace('.ts', '').replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
    lines.push(`  describe('${displayName}', () => {`);
    // Express's Router() returns a function (callable middleware) with
    // attached methods, so the framework-shaped assertion is on its type.
    lines.push(`    it('exports an Express router as default', () => {`);
    lines.push(`      expect(${importName}).toBeDefined();`);
    lines.push(`      expect(typeof ${importName}).toBe('function');`);
    lines.push(`    });`);
    lines.push(`  });`);
  }

  lines.push(`});`);
  lines.push(``);
  return lines.join('\n');
}

