// ─── Server entry generator ─────────────────────────────────────────────────

function generateExpressServerEntry(routes: RouteWiring[]): string {
  const routeImports = routes.map(r => `import ${r.importName} from '${r.importPath}';`);
  const routeMounts = routes.map(r => `mount('${r.mountPath}', ${r.importName});`);
  return [
    `import { app, mount } from './app.js';`,
    `import { runMigrations } from './db.js';`,
    ``,
    `// Generated route modules`,
    ...routeImports,
    ``,
    `// Mount routes`,
    ...routeMounts,
    ``,
    `// JSON 404 fallback — must be after all mounts (Express middleware`,
    `// runs in registration order). Aligns with the Hono target's notFound.`,
    `app.use((_req, res) => { res.status(404).json({ error: 'Not Found' }); });`,
    ``,
    `const port = parseInt(process.env.PORT ?? '3000', 10);`,
    `runMigrations();`,
    `app.listen(port, () => {`,
    `  console.log(\`Server running at http://localhost:\${port}\`);`,
    `});`,
    ``,
  ].join('\n');
}

